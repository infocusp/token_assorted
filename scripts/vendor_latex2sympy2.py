"""Vendor latex2sympy2 1.9.1 and the antlr4 4.7.2 Python runtime it needs into
`third_party/official_evals/_latex2sympy2/`, so TheoremQA's official scorer runs at full fidelity
in the SAME environment as the OlympiadBench judge.

Why: latex2sympy2's parser (`gen/PS*.py`) was generated by ANTLR 4.7.2 and only deserializes under
the 4.7.2 runtime, while sympy's `parse_latex` (OlympiadBench's `AutoScoringJudge`) needs 4.11.
Both runtimes are called `antlr4`, so they cannot be installed side by side. The runtime is pure
Python, so we copy it under a private package name and point latex2sympy2 at that copy; the
installed `antlr4` (4.11) stays sympy's.

The ONLY edits to upstream code are import statements, and this script asserts as much:

* every ``from antlr4...`` statement (top-level and the ones inside function bodies — the runtime
  defers 17 imports, some on the lexer's hot path, which is why a `sys.modules` swap at import
  time would silently mix the two runtimes) is re-pointed at ``<PKG>.antlr4``;
* latex2sympy2's ``try: from gen.PS* ... except: from .gen.PS*`` block is reduced to its
  package-relative branch, so a top-level ``gen`` package (the latex2sympy2 wheel installs one)
  can never be picked up instead of the vendored parser;
* the runtime's two ``from typing.io import TextIO`` become ``from typing import TextIO``.
  ``typing.io`` was removed in Python 3.13 (the 4.7.2 runtime predates that), and on 3.10-3.12
  ``typing.io.TextIO is typing.TextIO`` -- it is only used as a parameter annotation -- so this
  is a no-op where the original imports at all.

Every other byte, including the CRLF line endings of the generated parser, is unchanged.
`MANIFEST.json` records the source hashes and the SHA-256 of every output file;
`tests/test_theoremqa_latex2sympy2.py` checks the committed tree against it offline.

Usage (needs network for the two pinned downloads, or a `--cache` dir that already holds them):
    python scripts/vendor_latex2sympy2.py            # rebuild in a temp dir; verify the tree matches
    python scripts/vendor_latex2sympy2.py --write    # (re)write the vendored tree
"""
import argparse
import hashlib
import io
import json
import re
import shutil
import sys
import tarfile
import tempfile
import urllib.request
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DEST = REPO / "third_party" / "official_evals" / "_latex2sympy2"
PKG = "third_party.official_evals._latex2sympy2"
# Hand-written files in DEST that this script neither generates nor checks.
OURS = {"__init__.py", ".gitattributes"}

SOURCES = {
    "antlr4-python3-runtime": {
        "version": "4.7.2",
        "url": "https://files.pythonhosted.org/packages/29/14/8ac135ec7cc9db3f768e2d032776718c6b23f74e63543f0974b4873500b2/antlr4-python3-runtime-4.7.2.tar.gz",
        "sha256": "168cdcec8fb9152e84a87ca6fd261b3d54c8f6358f42ab3b813b14a7193bb50b",
        "license": "BSD-3-Clause",
    },
    "latex2sympy2": {
        "version": "1.9.1",
        "url": "https://files.pythonhosted.org/packages/0c/9e/4520682ab29a9219f1845643fdc75f1453bebf4b602c6e4421579de1f05d/latex2sympy2-1.9.1-py3-none-any.whl",
        "sha256": "44f24d263d235164a91173167a30d449f4360e3f0a59239ce6b843c50a41c601",
        "license": "MIT",
    },
    # The antlr4 sdist ships no license file; this is the one at the matching upstream tag.
    "antlr4-license": {
        "version": "4.7.2",
        "url": "https://raw.githubusercontent.com/antlr/antlr4/4.7.2/LICENSE.txt",
        "sha256": "b1b379fcaf3219593a4c433feb1b35c780bed23fafaae440b1ae2771a9521e3a",
        "license": "BSD-3-Clause",
    },
}
ANTLR_SDIST_PREFIX = "antlr4-python3-runtime-4.7.2/src/antlr4/"
L2S_WHEEL_FILES = ["latex2sympy2.py", "gen/__init__.py", "gen/PSLexer.py", "gen/PSParser.py",
                   "gen/PSListener.py"]
L2S_LICENSE = "latex2sympy2-1.9.1.dist-info/LICENSE.txt"

_FROM_ANTLR4 = re.compile(r"^(\s*)from antlr4(?=[.\s])")
_IMPORT_ANTLR4 = re.compile(r"^\s*import antlr4\b")
_TYPING_IO_OLD = "from typing.io import TextIO"
_TYPING_IO_NEW = "from typing import TextIO"
_N_TYPING_IO = 2  # antlr4/Lexer.py, antlr4/Parser.py
_GEN_BLOCK_OLD = (
    "try:\n"
    "    from gen.PSParser import PSParser\n"
    "    from gen.PSLexer import PSLexer\n"
    "    from gen.PSListener import PSListener\n"
    "except Exception:\n"
    "    from .gen.PSParser import PSParser\n"
    "    from .gen.PSLexer import PSLexer\n"
    "    from .gen.PSListener import PSListener\n"
)
_GEN_BLOCK_NEW = (
    "from .gen.PSParser import PSParser\n"
    "from .gen.PSLexer import PSLexer\n"
    "from .gen.PSListener import PSListener\n"
)


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _fetch(name: str, cache: Path | None) -> bytes:
    src = SOURCES[name]
    cached = cache / Path(src["url"]).name if cache else None
    if cached and cached.exists():
        data = cached.read_bytes()
    else:
        with urllib.request.urlopen(src["url"], timeout=60) as r:
            data = r.read()
        if cached:
            cache.mkdir(parents=True, exist_ok=True)
            cached.write_bytes(data)
    got = _sha256(data)
    if got != src["sha256"]:
        sys.exit(f"{name}: sha256 mismatch ({got} != pinned {src['sha256']}) - refusing to vendor")
    return data


def _rewrite_line(line: str) -> str:
    line = _FROM_ANTLR4.sub(lambda m: f"{m.group(1)}from {PKG}.antlr4", line)
    if line.strip() == _TYPING_IO_OLD:
        line = line.replace(_TYPING_IO_OLD, _TYPING_IO_NEW)
    return line


def _rewrite_imports(rel: str, data: bytes) -> tuple[bytes, int, int]:
    """Re-point every `from antlr4...` statement and the `typing.io` import; refuse any import
    form we do not rewrite. Returns (bytes, n_antlr4_lines, n_typing_io_lines)."""
    out, n_antlr, n_tio = [], 0, 0
    for line in data.decode("utf-8").splitlines(keepends=True):
        if _IMPORT_ANTLR4.match(line):
            # `import antlr4.x` binds the name `antlr4`; re-pointing it would need code edits too.
            sys.exit(f"{rel}: unsupported `import antlr4` statement: {line.strip()!r}")
        if "typing.io" in line and line.strip() != _TYPING_IO_OLD:
            sys.exit(f"{rel}: unsupported `typing.io` use: {line.strip()!r}")
        new = _rewrite_line(line)
        n_tio += line.strip() == _TYPING_IO_OLD
        n_antlr += new != line and line.strip() != _TYPING_IO_OLD
        out.append(new)
    text = "".join(out)
    leftover = [ln for ln in text.splitlines()
                if re.match(r"^\s*(from|import) antlr4\b", ln) or "typing.io" in ln]
    assert not leftover, (rel, leftover)
    return text.encode("utf-8"), n_antlr, n_tio


def _only_import_lines_changed(rel: str, old: bytes, new: bytes) -> None:
    a = old.decode("utf-8").splitlines(keepends=True)
    b = new.decode("utf-8").splitlines(keepends=True)
    if rel == "latex2sympy2.py":  # the one block-level edit, checked exactly
        a = "".join(a).replace(_GEN_BLOCK_OLD, _GEN_BLOCK_NEW).splitlines(keepends=True)
    assert len(a) == len(b), rel
    for x, y in zip(a, b):
        if x != y:
            assert (_FROM_ANTLR4.match(x) or x.strip() == _TYPING_IO_OLD) and y == _rewrite_line(x), \
                (rel, x, y)


def build(out: Path, cache: Path | None) -> dict:
    """Write the vendored tree (minus OURS) into `out`; return the manifest."""
    files: dict[str, bytes] = {}
    n_import_lines = n_typing_io = 0

    with tarfile.open(fileobj=io.BytesIO(_fetch("antlr4-python3-runtime", cache)), mode="r:gz") as tf:
        members = [m for m in tf.getmembers() if m.isfile() and m.name.startswith(ANTLR_SDIST_PREFIX)]
        assert members and all(m.name.endswith(".py") for m in members), "unexpected sdist layout"
        for m in members:
            rel = "antlr4/" + m.name[len(ANTLR_SDIST_PREFIX):]
            orig = tf.extractfile(m).read()
            files[rel], n, t = _rewrite_imports(rel, orig)
            _only_import_lines_changed(rel, orig, files[rel])
            n_import_lines += n
            n_typing_io += t

    with zipfile.ZipFile(io.BytesIO(_fetch("latex2sympy2", cache))) as zf:
        for rel in L2S_WHEEL_FILES:
            orig = zf.read(rel)
            data = orig
            if rel == "latex2sympy2.py":
                text = data.decode("utf-8")
                assert text.count(_GEN_BLOCK_OLD) == 1, "latex2sympy2.py gen-import block not found"
                data = text.replace(_GEN_BLOCK_OLD, _GEN_BLOCK_NEW).encode("utf-8")
            files[rel], n, t = _rewrite_imports(rel, data)
            _only_import_lines_changed(rel, orig, files[rel])
            n_import_lines += n
            n_typing_io += t
        files["LICENSE-latex2sympy2.txt"] = zf.read(L2S_LICENSE)
    files["LICENSE-antlr4.txt"] = _fetch("antlr4-license", cache)
    assert n_typing_io == _N_TYPING_IO, f"expected {_N_TYPING_IO} typing.io imports, saw {n_typing_io}"

    for rel, data in files.items():
        p = out / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
    manifest = {
        "generated_by": "scripts/vendor_latex2sympy2.py",
        "package": PKG,
        "sources": SOURCES,
        "edits": {
            "antlr4_import_lines_repointed": n_import_lines,
            "latex2sympy2_gen_import_block_made_relative": 1,
            "typing_io_TextIO_to_typing_TextIO": n_typing_io,
            "note": "import statements only; every other byte is upstream's",
        },
        "files": {rel: _sha256(files[rel]) for rel in sorted(files)},
    }
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


def _tree(root: Path) -> dict[str, bytes]:
    return {p.relative_to(root).as_posix(): p.read_bytes() for p in sorted(root.rglob("*"))
            if p.is_file() and "__pycache__" not in p.parts and p.relative_to(root).as_posix() not in OURS}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="(re)write the vendored tree in place")
    ap.add_argument("--cache", type=Path, help="directory to read/write the pinned downloads")
    args = ap.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        manifest = build(Path(tmp), args.cache)
        built = _tree(Path(tmp))
        if args.write:
            DEST.mkdir(parents=True, exist_ok=True)
            for p in list(DEST.iterdir()):
                if p.name not in OURS:
                    shutil.rmtree(p) if p.is_dir() else p.unlink()
            for rel, data in built.items():
                (DEST / rel).parent.mkdir(parents=True, exist_ok=True)
                (DEST / rel).write_bytes(data)
            print(f"wrote {len(built)} files to {DEST.relative_to(REPO)} "
                  f"({manifest['edits']['antlr4_import_lines_repointed']} import lines re-pointed)")
            return
        have = _tree(DEST) if DEST.exists() else {}
        bad = sorted(set(built) ^ set(have)) + sorted(r for r in built if r in have and built[r] != have[r])
        if bad:
            sys.exit(f"vendored tree differs from a fresh build in {len(bad)} file(s): {bad[:10]}")
        print(f"OK: {DEST.relative_to(REPO)} matches a fresh build from the pinned sources "
              f"({len(built)} files)")


if __name__ == "__main__":
    main()
